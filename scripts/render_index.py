#!/usr/bin/env python3
"""Render ``docs/work/INDEX.md`` from the per-item metadata files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "docs" / "work"
INDEX = WORK / "INDEX.md"

HEADER = """# Work items

Generated by `scripts/render_index.py`; do not edit by hand.

| ID | Type | Status | Title (EN) | 标题（中文） | EN | zh-CN | Issue |
|----|------|--------|------------|--------------|----|-------|-------|
"""


def load_items() -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    for meta_path in sorted(WORK.glob("*/meta.json")):
        if meta_path.parent.name.startswith("_"):
            continue
        items.append(json.loads(meta_path.read_text(encoding="utf-8")))
    return items


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(items: list[dict[str, object]]) -> str:
    lines = [HEADER.rstrip("\n")]
    for item in items:
        item_id = cell(item["id"])
        issue = f"#{item['issue']}" if item.get("issue") else "—"
        lines.append(
            f"| {item_id} | {cell(item['type'])} | {cell(item['status'])} | "
            f"{cell(item['title_en'])} | {cell(item['title_zh'])} | "
            f"[en]({item_id}/en.md) | [zh-CN]({item_id}/zh-CN.md) | {issue} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if INDEX.md is stale")
    args = parser.parse_args()

    content = render(load_items())
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            raise SystemExit("docs/work/INDEX.md is stale; run `make docs-index`")
        return
    INDEX.write_text(content, encoding="utf-8")
    print(INDEX)


if __name__ == "__main__":
    main()
